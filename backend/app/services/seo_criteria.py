def seo_category_frame(
    category: str,
    metrics_by_topic: dict[str, dict],
    issue_detail: pd.DataFrame | None = None,
    crawl_summary: dict | None = None,
    max_issues_per_topic: int = 5,
) -> pd.DataFrame:
    """Build the frame for one SEO category.

    metrics_by_topic: topic -> {metric: value}, as defined in SEO_TOPIC_METRICS. Topics without
    metrics still get a row (status_computed = None) so the specialist sees every topic.
    issue_detail: optional frame with columns topic, sf_category, issue_name, issue_type,
    issue_priority, urls, indexable_urls (from sf_issues_overview + sf_issue_map).

    One row per topic keeps the frame small: pass max_rows >= rows to _summarise_df, whose
    default of 50 split across sources would otherwise cut topics off.
    """
    topics = SEO_CATEGORY_TOPICS[category]
    frames = []
    if crawl_summary:
        frames.append(pd.DataFrame([{**crawl_summary, "_summary": True, "_source": "crawl_summary"}]))
    rows = []
    for topic in topics:
        metrics = metrics_by_topic.get(topic, {})
        status, rule = evaluate_topic(topic, metrics)
        rows.append({"topic": topic, "status_computed": status, "rule": rule,
                     "metrics": metrics, "_source": "topic_results"})
    frames.append(pd.DataFrame(rows))
    if issue_detail is not None and not issue_detail.empty:
        d = issue_detail[issue_detail["topic"].isin(topics) & (issue_detail["urls"] > 0)]
        d = (d.sort_values("urls", ascending=False)
              .groupby("topic", sort=False).head(max_issues_per_topic).copy())
        d["_source"] = "issue_detail"
        frames.append(d)
    return pd.concat(frames, ignore_index=True)


