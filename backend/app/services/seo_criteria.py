# Scoring — replaces scoring._compute_python for SEO
# ---------------------------------------------------------------------------
# Topics without a real evaluation do not count towards scores or maturity.
_UNSCORED_SOURCES = {"no_data_source", "parse_error", "missing"}


def _get(result, field: str):
    """Read a field from a SpecialistResult or a plain dict."""
    return result.get(field) if isinstance(result, dict) else getattr(result, field, None)


def _set(result, field: str, value) -> None:
    """Write a field on a SpecialistResult or a plain dict."""
    if isinstance(result, dict):
        result[field] = value
    else:
        setattr(result, field, value)


def _is_na(result) -> bool:
    return bool(_get(result, "not_applicable")) or _get(result, "status") == "na"


def seo_ice_priority(impact: float, confidence: float, ease: float) -> float:
    """ICE average scaled to 0-10: the same formula as scoring.ice_priority()."""
    return round(min((impact + confidence + ease) / 3.0 * 2.0, 10.0), 2)


def seo_topic_level(topic: str) -> str:
    """SpecialistResult.level for an SEO topic: its fixed maturity tier, in lower case."""
    return SEO_TOPIC_TIER[topic].lower()


def seo_finalise_results(results: list, frame: pd.DataFrame) -> list:
    """Python decides the status, Gemini explains it. Call after the Gemini call for one category,
    with the frame from seo_category_frame().

    Per result: level = the topic's fixed tier. When status_computed is pass, warn or fail, that
    is the status. When it is "na", the topic gets not_applicable = True (status "pass", like the
    B2B feed stubs), so scoring skips it. When it is None, Gemini's judgement stands. Works on
    SpecialistResult objects and dicts; changes them in place and returns the same list.
    """
    rows = frame[frame["_source"] == "topic_results"] if "_source" in frame.columns else frame.iloc[0:0]
    computed = dict(zip(rows["topic"], rows["status_computed"])) if len(rows) else {}
    for r in results:
        topic = _get(r, "topic")
        if topic in SEO_TOPIC_TIER:
            _set(r, "level", seo_topic_level(topic))
        status = computed.get(topic)
        if status in ("pass", "warn", "fail"):
            _set(r, "status", status)
            _set(r, "not_applicable", False)
        elif status == "na":
            _set(r, "status", "pass")
            _set(r, "not_applicable", True)
            _set(r, "action", "None")
    return results


def _scored(results: list) -> list:
    return [r for r in results
            if _get(r, "status") in ("pass", "warn", "fail")
            and not _is_na(r)
            and _get(r, "topic") not in SEO_REPORT_ONLY
            and _get(r, "source") not in _UNSCORED_SOURCES]


def seo_maturity(
    results: list,
    threshold: float = SEO_MATURITY_THRESHOLD,
    warn_weight: float = SEO_WARN_WEIGHT,
) -> dict:
    """Maturity staircase.

    Tier score = (pass + warn_weight × warn) / (pass + warn + fail) over the scored topics of that
    tier (n/a, report-only and no-data topics are left out). A tier is reached when its score
    meets the threshold and every lower tier is reached; a tier without scored topics counts as
    reached. The level is the highest tier reached; basic_complete is False when even Basic is
    not reached (the label is then still "Basic", the lowest label the app knows).
    """
    scored = _scored(results)
    tiers, level, below_reached = {}, None, True
    for tier, _ in SEO_TIERS:
        rows = [r for r in scored if SEO_TOPIC_TIER.get(_get(r, "topic")) == tier]
        counts = {s: sum(1 for r in rows if _get(r, "status") == s) for s in ("pass", "warn", "fail")}
        total = sum(counts.values())
        score = (counts["pass"] + warn_weight * counts["warn"]) / total if total else None
        reached = below_reached and (score is None or score >= threshold)
        below_reached = reached
        if reached:
            level = tier
        tiers[tier] = {**counts, "score": None if score is None else round(score, 3), "reached": reached}
    return {"level": level or "Basic", "basic_complete": level is not None, "tiers": tiers,
            "threshold": threshold, "warn_weight": warn_weight}


def seo_scoring(
    results: list,
    brand_model: str = "B2C",
    threshold: float = SEO_MATURITY_THRESHOLD,
    warn_weight: float = SEO_WARN_WEIGHT,
    max_wins: int = 10,
) -> dict:
    """ScoringOutput-compatible dict for SEO, plus "maturity" with the staircase detail.

    Category score = impact-weighted credit × 100 (pass 1, warn warn_weight, fail 0); pass_rate =
    share of scored topics that pass. Platform score = weighted mean of the category scores
    (SEO_BASE_WEIGHTS × business-model multiplier). maturity_label comes from seo_maturity(), not
    from the platform score. Quick wins: warn/fail topics (not n/a, not report-only) ranked by
    seo_ice_priority() = scoring.ice_priority(), ties broken by Impact. Like _compute_python,
    confidence is capped at 2 when the topic had no data (no_data_source, missing, parse_error).
    """
    multipliers = SEO_B2B_MULTIPLIERS if brand_model == "B2B" else SEO_B2C_D2C_MULTIPLIERS
    scored = _scored(results)
    credit = {"pass": 1.0, "warn": warn_weight, "fail": 0.0}
    category_scores, weighted, weights = [], 0.0, 0.0
    for category in SEO_CATEGORY_TOPICS:
        rows = [r for r in scored if _get(r, "category") == category]
        if not rows:
            continue
        impacts = [SEO_TOPIC_IMPACT.get(f"{category}::{_get(r, 'topic').lower()}", 3.0) for r in rows]
        score = 100 * sum(i * credit[_get(r, "status")] for i, r in zip(impacts, rows)) / sum(impacts)
        pass_rate = 100 * sum(1 for r in rows if _get(r, "status") == "pass") / len(rows)
        weight = SEO_BASE_WEIGHTS.get(category, 1.0) * multipliers.get(category, 1.0)
        category_scores.append({"name": category, "score": round(score, 1),
                                "pass_rate": round(pass_rate, 1), "weight": weight})
        weighted += score * weight
        weights += weight
    wins = []
    for r in results:
        if _get(r, "status") not in ("warn", "fail") or _is_na(r) or _get(r, "topic") in SEO_REPORT_ONLY:
            continue
        key = f"{_get(r, 'category')}::{_get(r, 'topic').lower()}"
        i, c, e = SEO_CRITERIA_ICE.get(key, (3.0, 3.0, 3.0))
        if _get(r, "source") in _UNSCORED_SOURCES:
            c = min(c, 2.0)
        wins.append({"topic": _get(r, "topic"), "category": _get(r, "category"), "impact": i,
                     "confidence": c, "ease": e, "priority_score": seo_ice_priority(i, c, e),
                     "action": _get(r, "action"), "explanation": _get(r, "explanation")})
    wins.sort(key=lambda w: (w["priority_score"], w["impact"]), reverse=True)
    maturity = seo_maturity(results, threshold, warn_weight)
    return {"platform_id": SEO_PLATFORM_ID, "category_scores": category_scores,
            "platform_score": round(weighted / weights, 1) if weights else 0.0, "omnichannel_score": None,
            "maturity_label": maturity["level"], "quick_wins": wins[:max_wins], "maturity": maturity}


