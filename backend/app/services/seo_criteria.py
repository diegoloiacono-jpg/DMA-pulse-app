# Rule evaluation — deterministic status from metrics (three-valued logic)
# ---------------------------------------------------------------------------
# A clause is True, False or None (unknown: a metric it needs is missing). Order:
#   na_if    any True  -> "na"
#   fail_if  any True  -> "fail"   (any unknown -> no verdict, Gemini decides)
#   warn_if  any True  -> "warn"   (any unknown -> no verdict)
#   pass_if  all True  -> "pass";  any False -> "warn";  otherwise no verdict
# Missing optional metrics make a clause False instead of unknown.

_CMP = {
    ast.Eq: operator.eq, ast.NotEq: operator.ne, ast.Lt: operator.lt, ast.LtE: operator.le,
    ast.Gt: operator.gt, ast.GtE: operator.ge,
    ast.In: lambda a, b: a in b, ast.NotIn: lambda a, b: a not in b,
}
_BIN = {ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul, ast.Div: operator.truediv}


def _value(node: ast.AST, metrics: dict):
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Name):
        v = metrics.get(node.id)
        return None if v is None or (isinstance(v, float) and v != v) else v
    if isinstance(node, ast.Tuple):
        return tuple(_value(e, metrics) for e in node.elts)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        v = _value(node.operand, metrics)
        return None if v is None else -v
    if isinstance(node, ast.BinOp) and type(node.op) in _BIN:
        a, b = _value(node.left, metrics), _value(node.right, metrics)
        if a is None or b is None or (isinstance(node.op, ast.Div) and b == 0):
            return None
        return _BIN[type(node.op)](a, b)
    raise ValueError(f"Unsupported expression: {ast.dump(node)}")


def _truth(node: ast.AST, metrics: dict) -> bool | None:
    if isinstance(node, ast.BoolOp):
        vals = [_truth(v, metrics) for v in node.values]
        if isinstance(node.op, ast.And):
            return False if False in vals else (None if None in vals else True)
        return True if True in vals else (None if None in vals else False)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
        v = _truth(node.operand, metrics)
        return None if v is None else not v
    if isinstance(node, ast.Compare):
        left = _value(node.left, metrics)
        result = True
        for op, comp in zip(node.ops, node.comparators):
            right = _value(comp, metrics)
            if left is None or right is None or (isinstance(right, tuple) and None in right):
                return None
            if not _CMP[type(op)](left, right):
                result = False
            left = right
        return result
    v = _value(node, metrics)
    return None if v is None else bool(v)


def _clause(expr: str, metrics: dict, optional: set[str]) -> bool | None:
    tree = ast.parse(expr, mode="eval").body
    v = _truth(tree, metrics)
    if v is None:
        names = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
        absent = {n for n in names if metrics.get(n) is None}
        if absent and absent <= optional:
            return False
    return v


def evaluate_topic(topic: str, metrics: dict) -> tuple[str | None, str]:
    """Return (status, rule) for one topic, or (None, reason) when the metrics are insufficient."""
    rules = SEO_RULES[topic]
    optional = SEO_OPTIONAL_METRICS.get(topic, set())
    if not metrics:
        return None, "no metrics"
    for expr in rules["na_if"]:
        v = _clause(expr, metrics, optional)
        if v is True:
            return "na", expr
        if v is None:
            return None, f"unknown: {expr}"
    unknown = None
    for expr in rules["fail_if"]:
        v = _clause(expr, metrics, optional)
        if v is True:
            return "fail", expr
        if v is None and unknown is None:
            unknown = expr
    if unknown:
        return None, f"unknown: {unknown}"
    for expr in rules["warn_if"]:
        v = _clause(expr, metrics, optional)
        if v is True:
            return "warn", expr
        if v is None:
            return None, f"unknown: {expr}"
    results = [(expr, _clause(expr, metrics, optional)) for expr in rules["pass_if"]]
    failed = [e for e, v in results if v is False]
    if failed:
        return "warn", f"pass condition not met: {failed[0]}"
    if all(v is True for _, v in results):
        return "pass", " and ".join(rules["pass_if"])
    return None, "unknown: " + next(e for e, v in results if v is None)


def seo_preconditions(metrics: dict) -> dict[str, dict]:
    """Check the preconditions before running the SEO pulse; they are not scored.

    Returns name -> {"met": True | False | None (unknown), "required": bool, "failed": first clause
    that is not met}. When a required one is not met, the Search Console based topics cannot be
    measured: report that up front instead of scoring those topics as warn.
    """
    out = {}
    for name, spec in SEO_PRECONDITIONS.items():
        checks = [(expr, _clause(expr, metrics, set())) for expr in spec["pass_if"]]
        failed = next((e for e, v in checks if v is False), None)
        met = False if failed else (True if all(v is True for _, v in checks) else None)
        out[name] = {"met": met, "required": spec["required"], "failed": failed}
    return out


def seo_data_gaps(search_console: bool = True) -> dict[str, list[str]]:
    """DATA_GAPS for one audit: SEO_DATA_GAPS plus, without Search Console access, the topics
    that cannot be measured without it (SEO_GSC_ONLY). The other Search Console topics then run
    on their fallback (SEO_GSC_FALLBACK) and stay measurable."""
    gaps = {k: list(v) for k, v in SEO_DATA_GAPS.items()}
    if not search_console:
        for category, topics in SEO_CATEGORY_TOPICS.items():
            for topic in topics:
                if topic in SEO_GSC_ONLY and topic not in gaps.get(category, []):
                    gaps.setdefault(category, []).append(topic)
    return gaps


